const maxFiles = 20_000;
const maxBytes = 100 * 1024 * 1024;
const maxLineSpan = 120;
const maxExcerpt = 3000;
const excludedDirectories = ['node_modules', 'vendor', 'vendors', 'dependencies', 'bower_components', 'site-packages',
  'dist', 'build', 'out', 'target', 'coverage', 'generated', '__generated__', '__pycache__', 'venv', 'locales',
  'locale', 'migrations', 'staticfiles'];
const excludedDirectory = (name: string) => name.startsWith('.') || excludedDirectories.includes(name.toLowerCase());
const languageGroups = {
  typescript: 'ts tsx mts cts', javascript: 'js jsx mjs cjs', python: 'py pyi', graphql: 'graphql gql',
  html: 'html htm jinja jinja2 j2 njk hbs ejs pug liquid', css: 'css scss sass less',
  ruby: 'rb erb rake', php: 'php blade', go: 'go', rust: 'rs', java: 'java', kotlin: 'kt kts',
  csharp: 'cs cshtml razor', c: 'c h cpp hpp cc', swift: 'swift', elixir: 'ex exs heex',
  vue: 'vue', svelte: 'svelte', shell: 'sh bash zsh fish', sql: 'sql', protobuf: 'proto',
  markdown: 'md mdx rst adoc txt feature', config: 'json jsonc yaml yml toml ini cfg conf properties xml prisma',
};
const languages = new Map(Object.entries(languageGroups).flatMap(([language, extensions]) =>
  extensions.split(' ').map(extension => [extension, language] as const)));
const credentialName = /(?:^|[._-])(?:credentials?|secrets?|private[-_]?keys?|service[-_]?accounts?|id_rsa|id_ed25519|passwd|htpasswd)(?:[._-]|$)/i;
const credentialContent = /-----BEGIN [A-Z ]*PRIVATE KEY-----|\b(?:sk-(?:proj-)?[\w-]{20,}|gh[pousr]_[a-z0-9]{20,}|github_pat_[\w]{20,}|(?:AKIA|ASIA)[A-Z0-9]{16}|xox[baprs]-[\w-]{12,})\b|\b[a-z][a-z\d+.-]*:\/\/[^\s:/@]+:[^\s/@]+@|\b(?:password|passwd|api[_-]?key|client[_-]?secret|access[_-]?token|secret[_-]?access[_-]?key)["']?\s*[:=]\s*["'][^"'\r\n]{8,}["']/i;
const generatedContent = /(?:^|\n)\s*(?:[/#*;!-]+\s*)?(?:@generated\b|code generated\b|auto[- ]generated\b|generated by .*do not edit)/i;
const git = promisify(execFile);
const decoder = new TextDecoder('utf-8', { fatal: true, ignoreBOM: true });
const contentByIndex = new WeakMap<RepositoryIndex, Map<string, string>>();

export function startupWorkspaces(index: RepositoryIndex, cwd?: string) {
  const packageNames = new Set(index.files
    .filter(file => file.kind === 'code' && posix.dirname(file.path) === (cwd ?? '.'))
    .flatMap(file => file.imports.map(name => name.split('/').slice(0, name.startsWith('@') ? 2 : 1).join('/'))));
  const workspaces: string[] = [];
  for (const { path } of index.files) {
    if (!path.endsWith('/package.json')) continue;
    const content = contentByIndex.get(index)?.get(path);
    if (!content) continue;
    try {
      const manifest = JSON.parse(content);
      if (packageNames.has(manifest?.name)) workspaces.push(posix.dirname(path));
    } catch {
      // Non-JSON package manifests cannot establish a workspace identity.
    }
  }
  return workspaces;
}

function candidate(path: string) {
  const parts = path.split('/');
  const name = parts.pop()!;
  if (path.length > 1000 || path.includes('\\') || /[\u0000-\u001f\u007f]/u.test(path) ||
      parts.some(part => !part || excludedDirectory(part) || credentialName.test(part)) ||
      !name || name.startsWith('.') || credentialName.test(name) ||
      /(?:^|[.-])lock(?:\.|$)|\.min\.|\.bundle\.|\.d\.[cm]?ts$|\.generated\.|^npm-shrinkwrap\.json$/i.test(name)) return;
  const extension = extname(name).slice(1).toLowerCase();
  const language = languages.get(extension) ??
    (/^(?:makefile|dockerfile|gemfile|procfile|rakefile)$/i.test(name) ? 'config' : undefined);
  if (!language) return;
  const kind: SourceFile['kind'] = parts.some(part => /^(?:__tests__|tests?|specs?|e2e|fixtures|testdata)$/i.test(part)) ||
      /(?:^test_|_test\.|\.(?:spec|test|stories|steps)\.|^conftest\.)/i.test(name) || extension === 'feature'
    ? 'test' : language === 'markdown' ? 'requirement' : language === 'config' ? 'config' : 'code';
  return { language, kind };
}

async function* walk(root: string, prefix = ''): AsyncGenerator<string> {
  const directory = resolve(root, prefix);
  if (await realpath(directory) !== directory) return;
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = prefix + entry.name;
    if (entry.isDirectory() && !excludedDirectory(entry.name) && !credentialName.test(entry.name)) {
      yield* walk(root, path + '/');
    } else {
      yield path;
    }
  }
}

async function pathsIn(root: string): Promise<Iterable<string> | AsyncIterable<string>> {
  try {
    const { stdout } = await git('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard',
      '--exclude=.*/', ...excludedDirectories.map(name => `--exclude=${name}/`)], {
      cwd: root, timeout: 20_000, maxBuffer: 32 * 1024 * 1024,
    });
    return new Set(stdout.split('\0').filter(Boolean));
  } catch (error) {
    if (error instanceof Error && error.message.includes('not a git repository')) return walk(root);
    throw new Error('Cannot enumerate repository files within the discovery limits');
  }
}

async function readContained(root: string, path: string, remainingBytes: number) {
  const absolute = join(root, path);
  if (!absolute.startsWith(root.endsWith(sep) ? root : root + sep)) return;
  try {
    // Equality also excludes symlinks whose targets happen to stay inside the repository.
    if (await realpath(absolute) !== absolute) return;
    const file = await open(absolute, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
    try {
      const stat = await file.stat();
      const pathStat = await lstat(absolute);
      if (!stat.isFile() || !pathStat.isFile() || pathStat.dev !== stat.dev || pathStat.ino !== stat.ino ||
          await realpath(absolute) !== absolute) return;
      if (stat.size > remainingBytes) throw new Error('Repository exceeds the 100 MB source budget');
      const bytes = Buffer.allocUnsafe(stat.size + 1);
      let offset = 0;
      while (offset < bytes.length) {
        const { bytesRead } = await file.read(bytes, offset, bytes.length - offset, offset);
        if (!bytesRead) break;
        offset += bytesRead;
      }
      if (offset !== stat.size) throw new Error('Repository source changed during discovery');
      const data = bytes.subarray(0, offset);
      if (data.includes(0)) return;
      let content: string;
      try { content = decoder.decode(data); } catch { return; }
      if (credentialContent.test(content) || generatedContent.test(content.slice(0, 4096))) return;
      return { content, bytes: offset, hash: createHash('sha256').update(data).digest('hex') };
    } finally {
      await file.close();
    }
  } catch (error) {
    if (error instanceof Error && 'code' in error && ['ELOOP', 'ENOENT', 'ENOTDIR'].includes(String(error.code))) return;
    throw error;
  }
}

function sourceLines(content: string) {
  return content ? content.replace(/(?:\r\n|\r|\n)$/, '').split(/\r\n|\r|\n/) : [];
}

function sourceLinks(path: string, language: string, content: string) {
  const symbols = new Set<string>();
  const imports = new Set<string>();
  if (language === 'typescript' || language === 'javascript') {
    const document = ts.createSourceFile(path, content, ts.ScriptTarget.Latest);
    const visit = (node: ts.Node) => {
      if (symbols.size >= 128 && imports.size >= 128) return;
      if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) && node.moduleSpecifier &&
          ts.isStringLiteralLike(node.moduleSpecifier)) imports.add(node.moduleSpecifier.text);
      if (ts.isCallExpression(node) && (node.expression.kind === ts.SyntaxKind.ImportKeyword ||
          ts.isIdentifier(node.expression) && node.expression.text === 'require')) {
        const name = node.arguments[0];
        if (name && ts.isStringLiteralLike(name)) imports.add(name.text);
      }
      if (symbols.size < 128 && (ts.isVariableDeclaration(node) || ts.isFunctionDeclaration(node) ||
          ts.isClassDeclaration(node) || ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node) ||
          ts.isMethodDeclaration(node) || ts.isEnumDeclaration(node)) && node.name && ts.isIdentifier(node.name)) {
        symbols.add(node.name.text);
      }
      ts.forEachChild(node, visit);
    };
    ts.forEachChild(document, visit);
  } else {
    for (const match of content.matchAll(/^\s*(?:export\s+)?(?:async\s+)?(?:def|class|function|func|fn|struct|interface|type|enum|scalar|input|directive|fragment|query|mutation|subscription|union)\s+@?([\w$-]+)/gm)) {
      symbols.add(match[1]);
      if (symbols.size >= 128) break;
    }
    for (const match of content.matchAll(/^\s*(?:from\s+([\w.]+)\s+import\b|(?:import|use|require|@import|#import)\s*["']?([\w./:@-]+))/gm)) {
      imports.add(match[1] ?? match[2]);
      if (imports.size >= 128) break;
    }
  }
  return { symbols: [...symbols].slice(0, 128), imports: [...imports].slice(0, 128) };
}

type FileDigest = Pick<SourceFile, 'path' | 'hash'>;
export const repositoryVersion = (files: FileDigest[]) => hashValue(files.map(({ path, hash }) => ({ path, hash })));

export function changedRepositoryPaths(current: FileDigest[], previous: FileDigest[]) {
  const old = new Map(previous.map(({ path, hash }) => [path, hash]));
  const changes = current.filter(({ path, hash }) => {
    const changed = old.get(path) !== hash;
    old.delete(path);
    return changed;
  }).map(({ path }) => path);
  return [...changes, ...old.keys()].sort();
}

export async function scanRepository(root: string, previous?: RepositoryIndex): Promise<RepositoryIndex> {
  const canonical = await realpath(root);
  const files: SourceFile[] = [];
  const content = new Map<string, string>();
  let size = 0;
  let lineCount = 0;
  let excludedFiles = 0;
  for await (const path of await pathsIn(canonical)) {
    const info = candidate(path);
    const source = info && await readContained(canonical, path, maxBytes - size);
    if (!info || !source) {
      excludedFiles++;
      continue;
    }
    if (files.length >= maxFiles) throw new Error('Repository exceeds the 20,000 file source budget');
    size += source.bytes;
    const lines = sourceLines(source.content).length;
    if (info.kind === 'code') lineCount += lines;
    files.push({ path, hash: source.hash, ...info, lines, ...sourceLinks(path, info.language, source.content) });
    content.set(path, source.content);
  }
  files.sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0);
  const index: RepositoryIndex = {
    root: canonical, files, version: repositoryVersion(files), sourceLines: lineCount, excludedFiles,
    indexedAt: new Date().toISOString(),
    changedPaths: changedRepositoryPaths(files, previous?.root === canonical ? previous.files : []),
  };
  contentByIndex.set(index, content);
  return index;
}

export function sourceReference(path: string, hash: string, content: string, startLine = 1, endLine?: number): SourceReference {
  const lines = sourceLines(content);
  const requestedEnd = endLine ?? startLine + maxLineSpan - 1;
  if (!Number.isSafeInteger(startLine) || !Number.isSafeInteger(requestedEnd) ||
      startLine < 1 || startLine > lines.length || requestedEnd < startLine) {
    throw new Error('Invalid source line range');
  }
  const maxEnd = Math.min(requestedEnd, startLine + maxLineSpan - 1, lines.length);
  const excerpt = lines.slice(startLine - 1, maxEnd).join('\n').slice(0, maxExcerpt);
  return { path, hash, startLine, endLine: startLine + excerpt.split('\n').length - 1, excerpt };
}

async function indexedContent(index: RepositoryIndex, file: SourceFile) {
  const source = candidate(file.path) && await readContained(index.root, file.path, maxBytes);
  if (!source || source.hash !== file.hash) throw new Error('Indexed source changed or is unavailable');
  return source.content;
}

export async function readRepositorySource(index: RepositoryIndex, path: string, startLine = 1, endLine?: number) {
  const file = index.files.find(file => file.path === path);
  if (!file) throw new Error('Path is outside the repository index');
  return sourceReference(path, file.hash, await indexedContent(index, file), startLine, endLine);
}

const stopWords = new Set(['a', 'an', 'and', 'by', 'for', 'in', 'of', 'on', 'or', 'the', 'to', 'with']);
function words(text: string) {
  return text.replace(/([a-z\d])([A-Z])/g, '$1 $2').toLowerCase().match(/[a-z0-9]+/g) ?? [];
}

export async function searchRepository(index: RepositoryIndex, query: string, limit = 8,
  relevance: (path: string) => number = () => 0): Promise<SourceReference[]> {
  const bounded = Number.isFinite(limit) ? Math.min(20, Math.floor(limit)) : 0;
  const terms = [...new Set(words(query.slice(0, 300)).filter(term => !stopWords.has(term)))].slice(0, 16);
  if (bounded < 1 || !terms.length) return [];
  const pattern = new RegExp(`\\b(?:${terms.join('|')})\\b`, 'g');
  const count = (text: string) => new Set((words(text.slice(0, maxExcerpt)).join(' ').match(pattern) ?? [])).size;
  const hits: { file: SourceFile; line: number; score: number; relevance: number }[] = [];
  const cached = contentByIndex.get(index);
  for (const file of index.files) {
    const content = cached?.get(file.path) ?? await indexedContent(index, file).catch(() => '');
    if (!content) continue;
    const lines = sourceLines(content);
    let best = 0;
    let line = 0;
    for (let i = 0; i < lines.length; i++) {
      const score = count(lines[i]);
      if (score > best) {
        best = score;
        line = i;
        if (score === terms.length) break;
      }
    }
    const symbols = file.symbols.join(' ');
    const covered = count([file.path, lines[line], symbols].join(' '));
    const score = best * 4 + count(file.path) * 3 + count(symbols) * 2;
    if (covered >= Math.ceil(terms.length / 2)) hits.push({ file, line, score, relevance: relevance(file.path) });
  }
  hits.sort((a, b) => b.relevance - a.relevance || b.score - a.score);
  const results: SourceReference[] = [];
  for (const { file, line } of hits) {
    const content = await indexedContent(index, file).catch(() => null);
    if (content === null) continue;
    const lines = sourceLines(content);
    // Keep the matched line inside the character budget even beside minified source.
    let start = line;
    while (start > Math.max(0, line - 3) && lines.slice(start - 1, line + 1).join('\n').length <= maxExcerpt) start--;
    results.push(sourceReference(file.path, file.hash, content, start + 1, line + 5));
    if (results.length >= bounded) break;
  }
  return results;
}
